import 'dart:math' as math;
import 'dart:ui';

/// One Fuse profile: a Netflix-style identity on the Fuse account, with
/// its own 4-digit PIN and its own Continue Watching / My List.
///
/// The server stores the record in `profiles:<email>`; the app caches the
/// list locally so the picker and the PIN work offline. The PIN itself is
/// never stored, sent, or logged — only its PBKDF2 record
/// (`v1$rounds$salt$hash`, see [AppLockPasscodeHash]), which the server
/// keeps verbatim and the device verifies locally.
///
/// Naming: `FuseProfile` / `fuseProfile(s)` everywhere, never bare
/// "profile" — the codebase already has `deviceProfileProvider` (the
/// TV/desktop *device* profile) and the two must never be confused.
class FuseProfile {
  const FuseProfile({
    required this.id,
    required this.name,
    required this.color,
    required this.pinRecord,
    required this.createdAt,
    required this.updatedAt,
  });

  /// `p_` + 16 hex chars, generated by the server.
  final String id;

  /// 1–20 chars, trimmed.
  final String name;

  /// A palette key (see [kFuseProfileColors]); no image assets.
  final String color;

  /// The PBKDF2 record for the profile's 4-digit PIN — hash only.
  final String pinRecord;

  final DateTime createdAt;
  final DateTime updatedAt;

  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name,
    'color': color,
    'pinRecord': pinRecord,
    'createdAt': createdAt.millisecondsSinceEpoch,
    'updatedAt': updatedAt.millisecondsSinceEpoch,
  };

  factory FuseProfile.fromJson(Map<String, dynamic> json) {
    return FuseProfile(
      id: json['id'] as String? ?? '',
      name: json['name'] as String? ?? '',
      color: json['color'] as String? ?? kFuseProfileDefaultColor,
      pinRecord: json['pinRecord'] as String? ?? '',
      createdAt: DateTime.fromMillisecondsSinceEpoch(
        (json['createdAt'] as num?)?.toInt() ?? 0,
      ),
      updatedAt: DateTime.fromMillisecondsSinceEpoch(
        (json['updatedAt'] as num?)?.toInt() ?? 0,
      ),
    );
  }

  FuseProfile copyWith({
    String? name,
    String? color,
    String? pinRecord,
    DateTime? updatedAt,
  }) => FuseProfile(
    id: id,
    name: name ?? this.name,
    color: color ?? this.color,
    pinRecord: pinRecord ?? this.pinRecord,
    createdAt: createdAt,
    updatedAt: updatedAt ?? this.updatedAt,
  );

  /// Usable as a tile: a real id and a PIN record to check against. A
  /// profile without a record (never opened on this device, offline)
  /// cannot be opened until one online open fetches it.
  bool get hasPinRecord => id.isNotEmpty && pinRecord.isNotEmpty;
}

/// A device-generated profile id, same shape as the server's (`p_` + 16
/// hex chars): local-only profiles (Build 2, logged-out users) get theirs
/// on this device, never from the server.
String newFuseProfileId() {
  final random = math.Random.secure();
  final bytes = List<int>.generate(8, (_) => random.nextInt(256));
  return 'p_${bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join()}';
}

/// PBKDF2 rounds for a profile PIN record: the account-password count,
/// stronger than the app lock's 10,000, because this record leaves the
/// device (it is stored on the server). See `AppLockPasscodeHash.create`.
const int kFuseProfilePinRounds = 100000;

/// Max profiles per account (Netflix allows 5). Min 1 — the last profile
/// cannot be deleted.
const int kFuseProfileMaxCount = 5;

/// The profile name the migration gives the first profile.
const String kFuseProfileDefaultName = 'My Profile';

/// The colour the migration gives the first profile: the first palette
/// colour.
const String kFuseProfileDefaultColor = 'gold';

/// The fixed 6-colour palette (the app's accent palette, no new assets).
/// The server validates membership; the app renders the colour.
const Map<String, Color> kFuseProfileColors = {
  'gold': Color(0xFFD4A017),
  'teal': Color(0xFF14B8A6),
  'red': Color(0xFFEF4444),
  'blue': Color(0xFF3B82F6),
  'purple': Color(0xFFA855F7),
  'green': Color(0xFF22C55E),
};

/// Whether [name] is a valid profile name: 1–20 chars after trimming.
String? fuseProfileNameError(String name) {
  final trimmed = name.trim();
  if (trimmed.isEmpty) return 'Enter a name for the profile.';
  if (trimmed.length > 20) return 'Name must be 20 characters or fewer.';
  return null;
}

/// The colour for a palette key, or gold for an unknown key (an old cache
/// must never crash the picker).
Color fuseProfileColor(String key) =>
    kFuseProfileColors[key] ?? kFuseProfileColors[kFuseProfileDefaultColor]!;

/// Local cache keys (settings box — `StorageService.setString`).
/// Device-local, never on the synced-settings allow-list: the list is
/// account data, not a setting, and must never be uploaded as part of a
/// backup. The active id is per device (phone can be on Dad, TV on
/// Kids) and is never synced either.
class FuseProfileCacheKeys {
  FuseProfileCacheKeys._();

  /// The last fetched profile list (JSON, incl. pinRecords, so the picker
  /// + PIN work offline). Shape: `{'profiles': [...], 'updatedAt': ms}`.
  static const String list = 'profiles_cache_json';

  /// The active profile on this device.
  static const String activeId = 'profiles_active_id';

  /// Whether the legacy data was migrated into the first profile.
  static const String migrated = 'profiles_migrated_v1';

  /// Per-profile failed PIN attempts in a row.
  static String attempts(String profileId) =>
      'profiles_pin_attempts_$profileId';

  /// Per-profile "no PIN accepted until" (unix ms); 0 for none.
  static String blockedUntil(String profileId) =>
      'profiles_pin_blocked_$profileId';

  /// Local-only profiles (Build 2, logged out): the list that lives on
  /// this device only, never on the server. Same JSON shape as [list].
  /// Kept apart from the server cache so logging in never overwrites
  /// local profiles and logging out never loses them.
  static const String localList = 'profiles_local_cache_json';

  /// The active local-only profile on this device.
  static const String localActiveId = 'profiles_local_active_id';
}
